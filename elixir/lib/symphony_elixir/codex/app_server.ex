defmodule SymphonyElixir.Codex.AppServer do
  @moduledoc """
  Minimal client for the Codex app-server JSON-RPC 2.0 stream over stdio.
  """

  @behaviour SymphonyElixir.AgentServer

  require Logger
  alias SymphonyElixir.AgentServer
  alias SymphonyElixir.AgentServer.WorkspaceGuard
  alias SymphonyElixir.{Codex.DynamicTool, Config, PathSafety, SSH}

  @initialize_id 1
  @thread_start_id 2
  @turn_start_id 3
  @port_line_bytes 1_048_576
  @max_stream_log_bytes 1_000
  @type session :: %{
          port: port(),
          metadata: map(),
          approval_policy: String.t() | map(),
          auto_approve_requests: boolean(),
          thread_sandbox: String.t(),
          turn_sandbox_policy: map(),
          thread_id: String.t(),
          workspace: Path.t(),
          workspace_root: Path.t(),
          worker_host: String.t() | nil,
          dynamic_tool_binding: map()
        }

  @spec run(Path.t(), String.t(), map(), keyword()) :: {:ok, map()} | {:error, AgentServer.Error.t()}
  def run(workspace, prompt, issue, opts \\ []) do
    with {:ok, session} <- start_session(workspace, opts) do
      try do
        run_turn(session, prompt, issue, legacy_callback_opts(opts))
      after
        stop_session(session)
      end
    end
  end

  @impl true
  def start_session(workspace, opts \\ []) do
    worker_host = Keyword.get(opts, :worker_host)
    effort = Keyword.get(opts, :effort)
    dynamic_tool_binding = DynamicTool.bind()

    result =
      with {:ok, %{workspace: expanded_workspace, workspace_root: workspace_root}} <-
             validate_workspace_context(workspace, worker_host),
           {:ok, port} <- start_port(expanded_workspace, worker_host, dynamic_tool_binding, effort) do
        metadata = port_metadata(port, worker_host)

        with {:ok, session_policies} <- session_policies(expanded_workspace, worker_host),
             {:ok, thread_id} <-
               do_start_session(port, expanded_workspace, session_policies, dynamic_tool_binding) do
          {:ok,
           %{
             port: port,
             metadata: metadata,
             approval_policy: session_policies.approval_policy,
             auto_approve_requests: session_policies.approval_policy == "never",
             thread_sandbox: session_policies.thread_sandbox,
             turn_sandbox_policy: session_policies.turn_sandbox_policy,
             thread_id: thread_id,
             workspace: expanded_workspace,
             workspace_root: workspace_root,
             worker_host: worker_host,
             dynamic_tool_binding: dynamic_tool_binding
           }}
        else
          {:error, reason} ->
            stop_port(port)
            {:error, reason}
        end
      end

    normalize_backend_result(result, :startup)
  end

  @impl true
  def run_turn(
        %{
          port: port,
          metadata: metadata,
          approval_policy: approval_policy,
          auto_approve_requests: auto_approve_requests,
          turn_sandbox_policy: turn_sandbox_policy,
          thread_id: thread_id,
          workspace: workspace,
          workspace_root: workspace_root,
          worker_host: worker_host,
          dynamic_tool_binding: dynamic_tool_binding
        },
        prompt,
        issue,
        opts \\ []
      ) do
    on_message = Keyword.get(opts, :on_message, &default_on_message/1)

    tool_executor =
      Keyword.get(opts, :tool_executor, fn tool, arguments ->
        DynamicTool.execute(tool, arguments, dynamic_tool_binding, issue: issue)
      end)

    result =
      case validate_turn_workspace(workspace, worker_host, workspace_root) do
        {:ok, safe_workspace} ->
          run_validated_turn(%{
            port: port,
            metadata: metadata,
            approval_policy: approval_policy,
            auto_approve_requests: auto_approve_requests,
            turn_sandbox_policy: turn_sandbox_policy,
            thread_id: thread_id,
            workspace: safe_workspace,
            prompt: prompt,
            issue: issue,
            on_message: on_message,
            tool_executor: tool_executor
          })

        {:error, reason} ->
          error = AgentServer.normalize_error(reason, :startup)
          Logger.error("Codex session workspace validation failed for #{issue_context(issue)} kind=#{error.kind} code=#{inspect(error.code)}")
          emit_message(on_message, :startup_failed, %{reason: reason, error: error}, metadata)
          {:error, error}
      end

    normalize_backend_result(result, :provider)
  end

  defp run_validated_turn(%{
         port: port,
         metadata: metadata,
         approval_policy: approval_policy,
         auto_approve_requests: auto_approve_requests,
         turn_sandbox_policy: turn_sandbox_policy,
         thread_id: thread_id,
         workspace: workspace,
         prompt: prompt,
         issue: issue,
         on_message: on_message,
         tool_executor: tool_executor
       }) do
    case start_turn(port, thread_id, prompt, issue, workspace, approval_policy, turn_sandbox_policy) do
      {:ok, turn_id} ->
        session_id = "#{thread_id}-#{turn_id}"
        Logger.info("Codex session started for #{issue_context(issue)} session_id=#{session_id}")

        emit_message(
          on_message,
          :session_started,
          %{
            session_id: session_id,
            thread_id: thread_id,
            turn_id: turn_id
          },
          metadata
        )

        port
        |> await_turn_completion(on_message, tool_executor, auto_approve_requests)
        |> finish_turn(issue, session_id, thread_id, turn_id, on_message, metadata)

      {:error, reason} ->
        error = AgentServer.normalize_error(reason, :startup)
        Logger.error("Codex session failed for #{issue_context(issue)}: kind=#{error.kind} code=#{inspect(error.code)}")
        emit_message(on_message, :startup_failed, %{reason: reason, error: error}, metadata)
        {:error, error}
    end
  end

  defp finish_turn({:ok, result}, issue, session_id, thread_id, turn_id, _on_message, _metadata) do
    Logger.info("Codex session completed for #{issue_context(issue)} session_id=#{session_id}")

    {:ok,
     %{
       result: result,
       session_id: session_id,
       thread_id: thread_id,
       turn_id: turn_id
     }}
  end

  defp finish_turn({:error, reason}, issue, session_id, _thread_id, _turn_id, on_message, metadata) do
    error = AgentServer.normalize_error(reason)
    event = if error.kind == :cancelled, do: :turn_cancelled, else: :turn_ended_with_error

    Logger.warning("Codex session ended with error for #{issue_context(issue)} session_id=#{session_id}: kind=#{error.kind} code=#{inspect(error.code)}")

    emit_message(
      on_message,
      event,
      %{
        session_id: session_id,
        reason: reason,
        error: error
      },
      metadata
    )

    {:error, error}
  end

  @impl true
  def stop_session(%{port: port}) when is_port(port) do
    stop_port(port)
  end

  defp validate_workspace_context(workspace, nil) when is_binary(workspace) do
    workspace_root = Config.local_workspace_root()

    with {:ok, canonical_workspace} <- WorkspaceGuard.validate(workspace, nil, workspace_root),
         {:ok, canonical_root} <- PathSafety.canonicalize(workspace_root) do
      {:ok, %{workspace: canonical_workspace, workspace_root: canonical_root}}
    end
  end

  defp validate_workspace_context(workspace, worker_host)
       when is_binary(workspace) and is_binary(worker_host) do
    WorkspaceGuard.validate_remote(workspace, worker_host, Config.settings!().workspace.root)
  end

  defp validate_turn_workspace(workspace, nil, workspace_root) do
    WorkspaceGuard.validate(workspace, nil, workspace_root)
  end

  defp validate_turn_workspace(workspace, worker_host, workspace_root) when is_binary(worker_host) do
    case WorkspaceGuard.validate_remote(workspace, worker_host, workspace_root) do
      {:ok, %{workspace: canonical_workspace}} -> {:ok, canonical_workspace}
      {:error, _reason} = error -> error
    end
  end

  defp start_port(workspace, nil, dynamic_tool_binding, effort) do
    executable = System.find_executable("bash")

    if is_nil(executable) do
      {:error, :bash_not_found}
    else
      port =
        Port.open(
          {:spawn_executable, String.to_charlist(executable)},
          [
            :binary,
            :exit_status,
            :stderr_to_stdout,
            args: [~c"-lc", String.to_charlist(local_launch_command(dynamic_tool_binding, effort))],
            cd: String.to_charlist(workspace),
            env: tracker_secret_port_env(dynamic_tool_binding),
            line: @port_line_bytes
          ]
        )

      {:ok, port}
    end
  end

  defp start_port(workspace, worker_host, dynamic_tool_binding, effort) when is_binary(worker_host) do
    remote_command = remote_launch_command(workspace, dynamic_tool_binding, effort)
    SSH.start_port(worker_host, remote_command, line: @port_line_bytes)
  end

  defp local_launch_command(dynamic_tool_binding, effort) do
    [
      tracker_secret_unset_command(dynamic_tool_binding),
      "exec #{apply_effort(Config.settings!().codex.command, effort)}"
    ]
    |> Enum.reject(&is_nil/1)
    |> Enum.join(" && ")
  end

  defp remote_launch_command(workspace, dynamic_tool_binding, effort) when is_binary(workspace) do
    [
      "cd #{shell_escape(workspace)}",
      tracker_secret_unset_command(dynamic_tool_binding),
      "exec #{apply_effort(Config.settings!().codex.command, effort)}"
    ]
    |> Enum.reject(&is_nil/1)
    |> Enum.join(" && ")
  end

  defp apply_effort(command, nil), do: command

  defp apply_effort(command, effort) when is_binary(effort) do
    if command =~ ~r/model_reasoning_effort\s*=\s*\S+/ do
      Regex.replace(~r/(model_reasoning_effort\s*=\s*)\S+/, command, "\\1#{effort}")
    else
      command <> " -c model_reasoning_effort=#{effort}"
    end
  end

  defp tracker_secret_port_env(dynamic_tool_binding) do
    dynamic_tool_binding.secret_environment_names
    |> valid_environment_names()
    |> Enum.map(fn name -> {String.to_charlist(name), false} end)
  end

  defp tracker_secret_unset_command(dynamic_tool_binding) do
    case dynamic_tool_binding.secret_environment_names |> valid_environment_names() do
      [] -> nil
      names -> "unset " <> Enum.join(names, " ")
    end
  end

  defp valid_environment_names(names) do
    Enum.filter(names, fn name ->
      is_binary(name) and String.match?(name, ~r/^[A-Za-z_][A-Za-z0-9_]*$/)
    end)
  end

  defp port_metadata(port, worker_host) when is_port(port) do
    base_metadata =
      case :erlang.port_info(port, :os_pid) do
        {:os_pid, os_pid} ->
          %{codex_app_server_pid: to_string(os_pid)}

        _ ->
          %{}
      end

    case worker_host do
      host when is_binary(host) -> Map.put(base_metadata, :worker_host, host)
      _ -> base_metadata
    end
  end

  defp send_initialize(port) do
    payload = %{
      "method" => "initialize",
      "id" => @initialize_id,
      "params" => %{
        "capabilities" => %{
          "experimentalApi" => true
        },
        "clientInfo" => %{
          "name" => "symphony-orchestrator",
          "title" => "Symphony Orchestrator",
          "version" => "0.1.0"
        }
      }
    }

    send_message(port, payload)

    with {:ok, _} <- await_response(port, @initialize_id) do
      send_message(port, %{"method" => "initialized", "params" => %{}})
      :ok
    end
  end

  defp session_policies(workspace, nil) do
    Config.codex_runtime_settings(workspace)
  end

  defp session_policies(workspace, worker_host) when is_binary(worker_host) do
    Config.codex_runtime_settings(workspace, remote: true)
  end

  defp do_start_session(port, workspace, session_policies, dynamic_tool_binding) do
    case send_initialize(port) do
      :ok -> start_thread(port, workspace, session_policies, dynamic_tool_binding)
      {:error, reason} -> {:error, reason}
    end
  end

  defp start_thread(
         port,
         workspace,
         %{approval_policy: approval_policy, thread_sandbox: thread_sandbox},
         dynamic_tool_binding
       ) do
    send_message(port, %{
      "method" => "thread/start",
      "id" => @thread_start_id,
      "params" => %{
        "approvalPolicy" => approval_policy,
        "sandbox" => thread_sandbox,
        "cwd" => workspace,
        "dynamicTools" => dynamic_tool_binding.tool_specs
      }
    })

    case await_response(port, @thread_start_id) do
      {:ok, %{"thread" => thread_payload}} ->
        case thread_payload do
          %{"id" => thread_id} -> {:ok, thread_id}
          _ -> {:error, {:invalid_thread_payload, thread_payload}}
        end

      other ->
        other
    end
  end

  defp start_turn(port, thread_id, prompt, issue, workspace, approval_policy, turn_sandbox_policy) do
    send_message(port, %{
      "method" => "turn/start",
      "id" => @turn_start_id,
      "params" => %{
        "threadId" => thread_id,
        "input" => [
          %{
            "type" => "text",
            "text" => prompt
          }
        ],
        "cwd" => workspace,
        "title" => "#{issue.identifier}: #{issue.title}",
        "approvalPolicy" => approval_policy,
        "sandboxPolicy" => turn_sandbox_policy
      }
    })

    case await_response(port, @turn_start_id) do
      {:ok, %{"turn" => %{"id" => turn_id}}} -> {:ok, turn_id}
      other -> other
    end
  end

  defp await_turn_completion(port, on_message, tool_executor, auto_approve_requests) do
    receive_loop(
      port,
      on_message,
      Config.settings!().codex.turn_timeout_ms,
      "",
      tool_executor,
      auto_approve_requests
    )
  end

  defp receive_loop(port, on_message, timeout_ms, pending_line, tool_executor, auto_approve_requests) do
    receive do
      {:agent_cancel, reason} ->
        {:error, cancellation_error(reason)}

      {^port, {:data, {:eol, chunk}}} ->
        complete_line = pending_line <> to_string(chunk)
        handle_incoming(port, on_message, complete_line, timeout_ms, tool_executor, auto_approve_requests)

      {^port, {:data, {:noeol, chunk}}} ->
        receive_loop(
          port,
          on_message,
          timeout_ms,
          pending_line <> to_string(chunk),
          tool_executor,
          auto_approve_requests
        )

      {^port, {:exit_status, status}} ->
        {:error, {:port_exit, status}}
    after
      timeout_ms ->
        {:error, :turn_timeout}
    end
  end

  defp handle_incoming(port, on_message, data, timeout_ms, tool_executor, auto_approve_requests) do
    payload_string = to_string(data)

    case Jason.decode(payload_string) do
      {:ok, %{"method" => "turn/completed"} = payload} ->
        emit_turn_event(on_message, :turn_completed, payload, payload_string, port, payload)
        {:ok, :turn_completed}

      {:ok, %{"method" => "turn/failed", "params" => _} = payload} ->
        emit_turn_event(
          on_message,
          :turn_failed,
          payload,
          payload_string,
          port,
          Map.get(payload, "params")
        )

        {:error, {:turn_failed, Map.get(payload, "params")}}

      {:ok, %{"method" => "turn/cancelled", "params" => _} = payload} ->
        emit_turn_event(
          on_message,
          :turn_cancelled,
          payload,
          payload_string,
          port,
          Map.get(payload, "params")
        )

        {:error, {:turn_cancelled, Map.get(payload, "params")}}

      {:ok, %{"method" => method} = payload}
      when is_binary(method) ->
        handle_turn_method(
          port,
          on_message,
          payload,
          payload_string,
          method,
          timeout_ms,
          tool_executor,
          auto_approve_requests
        )

      {:ok, payload} ->
        emit_message(
          on_message,
          :other_message,
          %{
            payload: payload,
            raw: payload_string
          },
          metadata_from_message(port, payload)
        )

        receive_loop(port, on_message, timeout_ms, "", tool_executor, auto_approve_requests)

      {:error, _reason} ->
        log_non_json_stream_line(payload_string, "turn stream")

        if protocol_message_candidate?(payload_string) do
          emit_message(
            on_message,
            :malformed,
            %{
              payload: payload_string,
              raw: payload_string
            },
            metadata_from_message(port, %{raw: payload_string})
          )
        end

        receive_loop(port, on_message, timeout_ms, "", tool_executor, auto_approve_requests)
    end
  end

  defp emit_turn_event(on_message, event, payload, payload_string, port, payload_details) do
    emit_message(
      on_message,
      event,
      %{
        payload: payload,
        raw: payload_string,
        details: payload_details
      },
      metadata_from_message(port, payload)
    )
  end

  defp handle_turn_method(
         port,
         on_message,
         payload,
         payload_string,
         method,
         timeout_ms,
         tool_executor,
         auto_approve_requests
       ) do
    metadata = metadata_from_message(port, payload)

    case maybe_handle_approval_request(
           port,
           method,
           payload,
           payload_string,
           on_message,
           metadata,
           tool_executor,
           auto_approve_requests
         ) do
      :input_required ->
        emit_message(
          on_message,
          :turn_input_required,
          %{payload: payload, raw: payload_string},
          metadata
        )

        {:error, {:turn_input_required, payload}}

      :approved ->
        receive_loop(port, on_message, timeout_ms, "", tool_executor, auto_approve_requests)

      :approval_required ->
        emit_message(
          on_message,
          :approval_required,
          %{payload: payload, raw: payload_string},
          metadata
        )

        {:error, {:approval_required, payload}}

      :unhandled ->
        if needs_input?(method, payload) do
          emit_message(
            on_message,
            :turn_input_required,
            %{payload: payload, raw: payload_string},
            metadata
          )

          {:error, {:turn_input_required, payload}}
        else
          emit_message(
            on_message,
            :notification,
            %{
              payload: payload,
              raw: payload_string
            },
            metadata
          )

          Logger.debug("Codex notification: #{inspect(method)}")
          receive_loop(port, on_message, timeout_ms, "", tool_executor, auto_approve_requests)
        end
    end
  end

  defp maybe_handle_approval_request(
         port,
         "item/commandExecution/requestApproval",
         %{"id" => id} = payload,
         payload_string,
         on_message,
         metadata,
         _tool_executor,
         auto_approve_requests
       ) do
    approve_or_require(
      port,
      id,
      "acceptForSession",
      payload,
      payload_string,
      on_message,
      metadata,
      auto_approve_requests
    )
  end

  defp maybe_handle_approval_request(
         port,
         "item/tool/call",
         %{"id" => id, "params" => params} = payload,
         payload_string,
         on_message,
         metadata,
         tool_executor,
         _auto_approve_requests
       ) do
    tool_name = tool_call_name(params)
    arguments = tool_call_arguments(params)

    result =
      tool_name
      |> tool_executor.(arguments)
      |> normalize_dynamic_tool_result()

    send_message(port, %{
      "id" => id,
      "result" => result
    })

    event =
      case result do
        %{"success" => true} -> :tool_call_completed
        _ when is_nil(tool_name) -> :unsupported_tool_call
        _ -> :tool_call_failed
      end

    emit_message(on_message, event, %{payload: payload, raw: payload_string}, metadata)

    :approved
  end

